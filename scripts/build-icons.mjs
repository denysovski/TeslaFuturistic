// Bundles only the icons the site uses, so <iconify-icon> never calls the Iconify API at runtime.
// Scans the pages, the page templates and the scripts for "prefix:name" and writes src/icons.generated.js.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { getIcons } from '@iconify/utils';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const SETS = ['solar', 'ph', 'brandico', 'logos'];
const scan = ['index.html', 'scripts/site', 'src'];
const found = new Map(SETS.map((s) => [s, new Set()]));
const re = new RegExp(`\\b(${SETS.join('|')}):([a-z0-9]+(?:-[a-z0-9]+)*)`, 'g');

function walk(p) {
  if (statSync(p).isDirectory()) return readdirSync(p).forEach((n) => walk(join(p, n)));
  if (!/\.(html|m?js)$/.test(p) || p.endsWith('icons.generated.js')) return;
  for (const [, set, name] of readFileSync(p, 'utf8').matchAll(re)) found.get(set).add(name);
}
scan.forEach(walk);

const collections = [];
for (const [set, names] of found) {
  if (!names.size) continue;
  const data = require(`@iconify-json/${set}/icons.json`);
  const subset = getIcons(data, [...names]);
  if (!subset) continue;
  const missing = [...names].filter((n) => !subset.icons[n] && !(subset.aliases || {})[n]);
  if (missing.length) console.warn(`missing in ${set}:`, missing.join(', '));
  collections.push(subset);
}
writeFileSync(
  'src/icons.generated.js',
  `// Generated by scripts/build-icons.mjs. Do not edit.\nimport { addCollection } from 'iconify-icon';\n${collections.map((c) => `addCollection(${JSON.stringify(c)});`).join('\n')}\n`,
);
console.log(`icons: ${collections.map((c) => `${c.prefix} ${Object.keys(c.icons).length}`).join(', ')}`);
